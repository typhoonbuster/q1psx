#!/usr/bin/env python3
"""Generate engine/q_trig_table.c — a 20.12 fixed-point sine table.

SINTAB_SIZE entries span a full turn; one extra entry is appended so the
interpolation in q_sin() can read table[idx + 1] without bounds checks.

Run from the repo root:  python3 tools/gen_sintab.py
"""
import math
import pathlib

SINTAB_SIZE = 1024
ONE = 4096  # 20.12

out = pathlib.Path("engine/q_trig_table.c")

vals = [round(math.sin(i * 2.0 * math.pi / SINTAB_SIZE) * ONE) for i in range(SINTAB_SIZE)]
vals.append(vals[0])  # wrap-around guard entry

lines = [
    "/*",
    " * q1psx — 20.12 fixed-point sine table.",
    " *",
    " * GENERATED by tools/gen_sintab.py — do not edit by hand.",
    f" * {SINTAB_SIZE} entries over a full turn (+1 wrap guard), 4096 == 1.0.",
    " */",
    "",
    '#include "q_trig_table.h"',
    "",
    f"const q_fixed q_sintab[Q_SINTAB_SIZE + 1] = {{",
]
for i in range(0, len(vals), 12):
    chunk = ", ".join(f"{v:6d}" for v in vals[i:i + 12])
    lines.append(f"\t{chunk},")
lines.append("};")
lines.append("")

out.write_text("\n".join(lines))
print(f"wrote {out} ({len(vals)} entries)")
