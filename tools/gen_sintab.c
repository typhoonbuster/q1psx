/*
 * Generate engine/q_trig_table.c — a 20.12 fixed-point sine table.
 *
 * SINTAB_SIZE entries span a full turn; one extra entry is appended so the
 * interpolation in q_sin() can read table[idx + 1] without a bounds check.
 *
 * Run from the repo root:  cc -O2 -o /tmp/gs tools/gen_sintab.c -lm && /tmp/gs
 * (or `make -C tools gen-sintab`).
 */

#include <math.h>
#include <stdio.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif

#define SINTAB_SIZE 1024
#define ONE         4096   /* 20.12 */

int main(void)
{
	FILE *f = fopen("engine/q_trig_table.c", "w");
	if (!f) {
		perror("engine/q_trig_table.c");
		return 1;
	}

	fputs("/*\n"
	      " * q1psx - 20.12 fixed-point sine table.\n"
	      " *\n"
	      " * GENERATED by tools/gen_sintab.c - do not edit by hand.\n"
	      " * 1024 entries over a full turn (+1 wrap guard), 4096 == 1.0.\n"
	      " */\n\n"
	      "#include \"q_trig_table.h\"\n\n"
	      "const q_fixed q_sintab[Q_SINTAB_SIZE + 1] = {\n", f);

	for (int i = 0; i <= SINTAB_SIZE; i++) {
		int v = (int) lround(sin((double) (i % SINTAB_SIZE) * 2.0 * M_PI / SINTAB_SIZE) * ONE);
		fprintf(f, "%s%6d,", (i % 12 == 0) ? "\t" : " ", v);
		if (i % 12 == 11)
			fputc('\n', f);
	}
	if (SINTAB_SIZE % 12 != 11)
		fputc('\n', f);

	fputs("};\n", f);
	fclose(f);

	printf("wrote engine/q_trig_table.c (%d entries)\n", SINTAB_SIZE + 1);
	return 0;
}
